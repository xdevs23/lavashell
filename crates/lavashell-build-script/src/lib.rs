//! The steps shared by the build scripts that generate code from a package located by an environment variable.
#![forbid(unsafe_code)]

use std::error::Error;
use std::path::PathBuf;
use std::process::ExitCode;
use std::{env, fs, io};

use lavashell_core::error::message_chain;

#[derive(Debug, thiserror::Error)]
pub enum BuildScriptError {
    #[error("{} is not set. Build inside `nix develop`, or set it to {}.", .0.name, .0.package)]
    PackageNotSet(PackageVariable),
    #[error("cargo does not set OUT_DIR. Run the build script through cargo.")]
    OutputDirectoryNotSet,
    #[error("cannot write {}", .file.display())]
    Write { file: PathBuf, source: io::Error },
}

/// An environment variable that contains the path of a package read by a build script.
#[derive(Clone, Copy, Debug)]
pub struct PackageVariable {
    pub name: &'static str,
    /// The name of the package that the variable points at. The error for an unset variable shows this name.
    pub package: &'static str,
}

impl PackageVariable {
    /// The path of the package. Cargo runs the build script again when the variable changes.
    ///
    /// # Errors
    /// Fails when the variable is not set.
    pub fn path(self) -> Result<PathBuf, BuildScriptError> {
        println!("cargo::rerun-if-env-changed={}", self.name);
        env::var_os(self.name)
            .map(PathBuf::from)
            .ok_or(BuildScriptError::PackageNotSet(self))
    }
}

/// The directory that cargo sets in `OUT_DIR` for the files generated by a build script.
///
/// # Errors
/// Fails when cargo does not set the directory.
pub fn output_directory() -> Result<PathBuf, BuildScriptError> {
    env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .ok_or(BuildScriptError::OutputDirectoryNotSet)
}

/// Writes `contents` to `file`, replacing the file if it exists.
///
/// # Errors
/// Fails when the file cannot be written.
pub fn write(file: PathBuf, contents: impl AsRef<[u8]>) -> Result<(), BuildScriptError> {
    fs::write(&file, contents).map_err(|source| BuildScriptError::Write { file, source })
}

/// Runs `generate` as the body of a build script. When `generate` fails, prints the error with its chain of causes to
/// stderr and returns `ExitCode::FAILURE`.
#[must_use]
pub fn run<E: Error>(generate: impl FnOnce() -> Result<(), E>) -> ExitCode {
    match generate() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("{}", message_chain(error));
            ExitCode::FAILURE
        }
    }
}
